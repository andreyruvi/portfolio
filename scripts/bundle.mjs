/**
 * bundle.mjs — packs the ES modules in js/ into one classic script.
 *
 * Why this exists: `<script type="module">` is fetched under CORS rules, and a
 * page opened straight from a folder (file://) has a null origin, so the browser
 * refuses to load it. The page still renders — it is pre-rendered HTML — but
 * every interactive part is dead: no Owner edit, no lightbox, no filters. That
 * is exactly what happens when someone double-clicks index.html or PREVIEW.bat.
 *
 * A classic script has no such restriction, so the site works identically from
 * a folder, from GitHub Pages, or from any other host.
 *
 * The modules stay the real source — Node imports them directly for the build,
 * and they are what you edit. js/bundle.js is generated, like the HTML.
 *
 * The transform is deliberately small, and only has to handle the import and
 * export forms this project actually uses:
 *
 *   import * as R from './render.js'      -> const R = __req('render')
 *   import { a, b } from './app.js'       -> const { a, b } = __req('app')
 *   export function foo() {}              -> function foo() {}   (+ exported)
 *   export const foo = …                  -> const foo = …       (+ exported)
 *   import('./editor.js')                 -> a resolved promise for the module
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/* Dependency order. A module may only reference ones already defined, except
   through the lazy `import()` in app.js, which resolves on demand. */
const MODULES = ['render', 'page', 'zip', 'app', 'editor'];

function transform(name, src) {
  const exported = new Set();

  let out = src
    // import * as R from './render.js';
    .replace(/^import\s+\*\s+as\s+(\w+)\s+from\s+'\.\/(\w+)\.js';$/gm,
      (_, alias, mod) => `const ${alias} = __req('${mod}');`)
    // import { a, b as c } from './app.js';
    .replace(/^import\s+\{([^}]+)\}\s+from\s+'\.\/(\w+)\.js';$/gm,
      (_, names, mod) => `const {${names}} = __req('${mod}');`)
    // dynamic import, used to load the editor only when it is needed
    .replace(/import\('\.\/(\w+)\.js'\)/g,
      (_, mod) => `Promise.resolve().then(() => __req('${mod}'))`);

  // export function / export async function
  out = out.replace(/^export\s+(async\s+)?function\s+(\w+)/gm, (_, asyncKw, fn) => {
    exported.add(fn);
    return `${asyncKw || ''}function ${fn}`;
  });
  // export const / let
  out = out.replace(/^export\s+(const|let)\s+(\w+)/gm, (_, kw, id) => {
    exported.add(id);
    return `${kw} ${id}`;
  });

  if (/^export\s/m.test(out)) {
    throw new Error(`${name}.js uses an export form the bundler does not handle:\n` +
      out.split('\n').filter((l) => /^export\s/.test(l)).join('\n'));
  }

  const assigns = [...exported].map((n) => `  __exports.${n} = ${n};`).join('\n');
  return `__def('${name}', function (__exports, __req) {\n${out}\n${assigns}\n});`;
}

const parts = MODULES.map((name) => {
  const src = fs.readFileSync(path.join(ROOT, 'js', `${name}.js`), 'utf8');
  return transform(name, src);
});

const bundle = `/* GENERATED by scripts/bundle.mjs — do not edit.
   Source of truth: js/render.js, js/page.js, js/zip.js, js/app.js, js/editor.js
   Built as a classic script so the site also works when opened from a folder. */
(function () {
  'use strict';
  var __registry = {};
  function __def(name, factory) { __registry[name] = { factory: factory, exports: null }; }
  function __req(name) {
    var m = __registry[name];
    if (!m) throw new Error('unknown module: ' + name);
    if (!m.exports) { m.exports = {}; m.factory(m.exports, __req); }
    return m.exports;
  }

${parts.join('\n\n')}

  __req('app');
})();
`;

fs.writeFileSync(path.join(ROOT, 'js/bundle.js'), bundle);
console.log(`bundled ${MODULES.length} modules -> js/bundle.js (${(Buffer.byteLength(bundle) / 1024).toFixed(1)} KB)`);
